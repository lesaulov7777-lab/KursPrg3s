#!/bin/bash
# tests/smoke.sh — автоматическая проверка программы audit (запускается через `make test`)
# Программа запускается в пустом временном каталоге, ввод подаётся из файлов.

BIN="$(cd "$(dirname "$0")/.." && pwd)/audit"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
cd "$WORK" || exit 1

PASS=0
FAIL=0
check() {  # check "описание" код_возврата
    if [ "$2" -eq 0 ]; then echo "  [ OK ] $1"; PASS=$((PASS + 1))
    else echo "  [FAIL] $1"; FAIL=$((FAIL + 1)); fi
}
has() { grep -qF -- "$1" out.txt; }   # есть ли строка в выводе программы

echo "Проверка программы аудита ИБ"

# 1. Первый запуск: создание администратора, три объекта (риск 9, 2 и 0), просмотр, поиск
cat > in1.txt <<'IN'
admin
Pass123
Pass123
admin
Pass123
1
УК-ПК-001
1
2
Иванова А. С.
Windows 10
27.10.2026
нет
нет
да

1
УК-СРВ-002
3
4
Петров П. П.
Ubuntu
27.10.2026
да
10.10.2026
да
нет

1
УК-НБ-003
2
1
Сидорова М. В.
Windows 11
27.10.2026
да
25.10.2026
да
да

2

3
УК-ПК-001

3
НЕТ-ТАКОГО

0
IN
"$BIN" < in1.txt > out.txt 2>&1
check "программа завершилась с кодом 0" $?
has "Администратор создан"; check "создан администратор" $?
has "Уровень риска: 9 (высокий)"; check "риск 9: нет антивируса, слабый пароль, ПДн" $?
has "Уровень риска: 2 (низкий)"; check "риск 2: устаревшие базы антивируса" $?
has "Уровень риска: 0 (низкий)"; check "риск 0: нарушений нет" $?
has "Всего объектов: 3"; check "в списке три объекта" $?
has "Объект с номером НЕТ-ТАКОГО не найден"; check "поиск несуществующего объекта" $?
grep -q "Pass123" users.dat; [ $? -ne 0 ]; check "пароль не хранится в users.dat" $?
SIZE=$(wc -c < audit.dat | tr -d ' ')
[ "$SIZE" -gt 0 ] && [ $((SIZE % 3)) -eq 0 ]; check "размер audit.dat кратен трём записям" $?

# 2. Отчёт: порог от 1 балла — 2 объекта, от 6 баллов — 1 объект
printf 'admin\nPass123\n6\n1\n\n7\n\n6\n3\n\n7\n\n0\n' | "$BIN" > out.txt 2>&1
has "Объектов в отчёте: 2"; check "отчёт с порогом 1: два объекта" $?
has "Объектов в отчёте: 1"; check "отчёт с порогом 6: один объект" $?

# 3. Фильтр и сортировка (фильтр по уровню риска «высокий»)
printf 'admin\nPass123\n8\n4\n3\n1\n\n0\n' | "$BIN" > out.txt 2>&1
has "Всего объектов: 1"; check "фильтр по высокому риску даёт один объект" $?

# 4. Корректировка: ноутбук без антивируса и без ПДн — риск 3 → пересчёт
printf 'admin\nPass123\n4\nУК-НБ-003\n5\nнет\n8\nнет\n0\n\n0\n' | "$BIN" > out.txt 2>&1
has "Изменения сохранены. Уровень риска: 4 (средний)"; check "корректировка пересчитывает риск" $?

# 5. Удаление: отказ и подтверждение
printf 'admin\nPass123\n5\nУК-СРВ-002\nнет\n\n5\nУК-СРВ-002\nда\n\n2\n\n0\n' | "$BIN" > out.txt 2>&1
has "Удаление отменено"; check "отказ от удаления" $?
has "Объект удалён"; check "удаление объекта" $?
has "Всего объектов: 2"; check "после удаления осталось два объекта" $?
[ ! -e audit.dat.tmp ]; check "временный файл удалён" $?

# 6. Вход: три неверных пароля
printf 'admin\nx\nadmin\ny\nadmin\nz\n' | "$BIN" > out.txt 2>&1
CODE=$?
has "Доступ запрещён"; check "три неверных пароля — доступ запрещён" $?
[ "$CODE" -eq 1 ]; check "код возврата 1 при отказе в доступе" $?

# 7. Повреждённый файл: обрезанный audit.dat
head -c 100 audit.dat > broken.dat && mv broken.dat audit.dat
printf 'admin\nPass123\n0\n' | "$BIN" > out.txt 2>&1
has "повреждён"; check "обрезанный audit.dat обнаружен" $?

echo
echo "Пройдено: $PASS, не пройдено: $FAIL"
[ "$FAIL" -eq 0 ]
