#!/bin/bash
# tests/smoke.sh — автоматическая проверка программы audit (запускается через `make test`)
# Программа запускается в пустом временном каталоге, ввод подаётся из файлов.

BIN="$(cd "$(dirname "$0")/.." && pwd)/audit"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
cd "$WORK" || exit 1

PASS=0
FAIL=0
check() {  # check "описание" код_возврата
    if [ "$2" -eq 0 ]; then echo "  [ OK ] $1"; PASS=$((PASS + 1))
    else echo "  [FAIL] $1"; FAIL=$((FAIL + 1)); fi
}
has() { grep -qF -- "$1" out.txt; }   # есть ли строка в выводе программы

echo "Проверка программы аудита ИБ"

# 1. Первый запуск: создание администратора, три объекта (риск 9, 2 и 0), просмотр, поиск
cat > in1.txt <<'IN'
admin
Pass123
Pass123
admin
Pass123
1
УК-ПК-001
1
2
Иванова А. С.
Windows 10
27.10.2026
нет
нет
да

1
УК-СРВ-002
3
4
Петров П. П.
Ubuntu
27.10.2026
да
10.10.2026
да
нет

1
УК-НБ-003
2
1
Сидорова М. В.
Windows 11
27.10.2026
да
25.10.2026
да
да

2

3
УК-ПК-001

3
НЕТ-ТАКОГО

0
IN
"$BIN" < in1.txt > out.txt 2>&1
check "программа завершилась с кодом 0" $?
has "Администратор создан"; check "создан администратор" $?
has "Уровень риска: 9 (высокий)"; check "риск 9: нет антивируса, слабый пароль, ПДн" $?
has "Уровень риска: 2 (низкий)"; check "риск 2: устаревшие базы антивируса" $?
has "Уровень риска: 0 (низкий)"; check "риск 0: нарушений нет" $?
has "Всего объектов: 3"; check "в списке три объекта" $?
has "Объект с номером НЕТ-ТАКОГО не найден"; check "поиск несуществующего объекта" $?
grep -q "Pass123" users.dat; [ $? -ne 0 ]; check "пароль не хранится в users.dat" $?
SIZE=$(wc -c < audit.dat | tr -d ' ')
[ "$SIZE" -gt 0 ] && [ $((SIZE % 3)) -eq 0 ]; check "размер audit.dat кратен трём записям" $?

# 2. Вход: три неверных пароля
printf 'admin\nx\nadmin\ny\nadmin\nz\n' | "$BIN" > out.txt 2>&1
CODE=$?
has "Доступ запрещён"; check "три неверных пароля — доступ запрещён" $?
[ "$CODE" -eq 1 ]; check "код возврата 1 при отказе в доступе" $?

echo
echo "Пройдено: $PASS, не пройдено: $FAIL"
[ "$FAIL" -eq 0 ]
